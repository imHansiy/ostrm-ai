import fs from 'node:fs';
process.on('unhandledRejection',error=>{console.error('SDK failure:',error?.message,new URL(error?.config?.url||'/',error?.config?.baseURL||'http://test').pathname);process.exit(1)});
import assert from 'node:assert/strict';
import {Jellyfin} from '@jellyfin/sdk';
import {getSystemApi} from '@jellyfin/sdk/lib/utils/api/system-api.js';
import {getUserApi} from '@jellyfin/sdk/lib/utils/api/user-api.js';
import {getUserViewsApi} from '@jellyfin/sdk/lib/utils/api/user-views-api.js';
import {getItemsApi} from '@jellyfin/sdk/lib/utils/api/items-api.js';
import {getMediaInfoApi} from '@jellyfin/sdk/lib/utils/api/media-info-api.js';
import {getPlaystateApi} from '@jellyfin/sdk/lib/utils/api/playstate-api.js';
const fixture=JSON.parse(fs.readFileSync(process.env.CLIENT_FIXTURE||'../../.local/integration/client.json','utf8'));
const sdk=new Jellyfin({clientInfo:{name:'OStrm AI contract test',version:'0.2.0'},deviceInfo:{name:'Node test',id:'sdk-test'}});
const api=sdk.createApi(fixture.links.jellyfin_server);
assert.equal((await getSystemApi(api).getPublicSystemInfo()).data.Version,'10.11.0');
const auth=await getUserApi(api).authenticateUserByName({authenticateUserByName:{Username:fixture.links.jellyfin_username,Pw:fixture.links.jellyfin_password}});
api.accessToken=auth.data.AccessToken;
const userId=auth.data.User.Id;
assert.equal((await getUserViewsApi(api).getUserViews({userId})).data.Items[0].Id,'library');
const items=(await getItemsApi(api).getItems({userId,recursive:true,limit:10})).data;
assert.equal(items.TotalRecordCount,1);const item=items.Items[0];
assert.ok(item.Overview.startsWith('蓝色画面'));assert.ok(item.Tags.includes('蓝色'));
const playback=(await getMediaInfoApi(api).getPlaybackInfo({itemId:item.Id,userId})).data;
assert.equal(playback.MediaSources[0].SupportsDirectPlay,true);
await getPlaystateApi(api).reportPlaybackProgress({playbackProgressInfo:{ItemId:item.Id,PositionTicks:12000000,IsPaused:true}});
const updated=(await getItemsApi(api).getItems({userId,ids:[item.Id]})).data.Items[0];
assert.equal(updated.UserData.PlaybackPositionTicks,12000000);
console.log('PASS: official @jellyfin/sdk 0.13 login, views, metadata, playback information, persisted progress');
